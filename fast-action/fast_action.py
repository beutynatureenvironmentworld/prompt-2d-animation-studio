 def __init__(self):
  self.motion=json.loads((OUT/'real-lineart-gait.json').read_text())
  assert self.motion.get('fps')==FPS and len(self.motion['rows'])>=SECONDS*FPS
  self.cues=json.loads((ASSETS/'rhubarb-mouth-cues.json').read_text())['mouthCues']
  self.heads=[]
  for i in range(1,25):
   p=ASSETS/f'face_{i:03d}.png'
   im=Image.open(p).convert('RGBA')
   bbox=im.getchannel('A').getbbox()
   im=im.crop(bbox)
   # Re-colour actual Iki-rigged, WebGL2-rendered facial poses into the
   # consistent pale ink-on-paper character art. The frames are NOT still copies.
   pixels=list(im.getdata()); processed=[]
   for r,g,b,a in pixels:
    if a==0:processed.append((0,0,0,0));continue
    bright=(r*.3+g*.59+b*.11)
    if bright<168:processed.append((*INK,a))
    else:processed.append((*CREAM,a))
   im.putdata(processed)
   self.heads.append(im.resize((101,111),Image.Resampling.LANCZOS))
  self.face_cues_used=set();self.pose_indices_used=set()
 def mouth(self,clock):
  if not 0<=clock<2.18:return 'X'
  for cue in self.cues:
   if cue['start']<=clock<cue['end']:
    self.face_cues_used.add(cue['value']);return cue['value']
  return 'X'
